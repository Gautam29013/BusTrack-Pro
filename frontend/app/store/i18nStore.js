const useI18nStore = create(
  persist(
    (set, get) => ({
      lang: 'en',
      setLang: (lang) => set({ lang }),
      // Translation function `t('key')`
      t: (key) => {
        const lang = get().lang;
        return dictionaries[lang]?.[key] || dictionaries['en'][key] || key;
      },
    }),
    {
      name: 'bustrakpro-lang',
    }
  )
);

export default useI18nStore;
